import type { CollectionConfig } from 'payload'
import {
  integer,
  assignLinkedCustomer,
  legacyId,
  legacyLabels,
  matchRelated,
  money,
  privateAccess,
  protectCustomerQuestionCreate,
  protectReferences,
  relation,
  staffManaged,
  staffOrAppUser,
  staffOrCustomer,
  validateRecord,
  workflow,
} from '../lib/voyage-schema'

export const CustomerQuestions: CollectionConfig = {
  slug: 'customer-questions',
  labels: { singular: 'Klantvraag', plural: 'Klantvragen' },
  admin: {
    group: 'Klantenservice',
    useAsTitle: 'reference',
    defaultColumns: ['reference', 'subject', 'customer', 'priority', 'status'],
  },
  access: {
    ...privateAccess,
    create: staffOrAppUser,
    read: staffOrCustomer(),
  },
  versions: false,
  hooks: {
    beforeValidate: [assignLinkedCustomer(), validateRecord],
    beforeChange: [
      protectCustomerQuestionCreate,
      matchRelated('booking', 'bookings', ['customer']),
    ],
    beforeDelete: [
      protectReferences([
        { collection: 'messages', field: 'question' },
        { collection: 'quotes', field: 'question' },
      ]),
    ],
  },
  fields: [
    legacyId(),
    {
      name: 'reference',
      label: 'Vraagnummer',
      type: 'text',
      required: true,
      unique: true,
    },
    relation('customer', 'Klant', 'customers'),
    { name: 'subject', label: 'Onderwerp', type: 'text', required: true },
    { name: 'message', label: 'Oorspronkelijk bericht', type: 'textarea', required: true },
    { name: 'category', label: 'Categorie', type: 'text', required: true, index: true },
    {
      name: 'channel',
      label: 'Kanaal',
      type: 'select',
      options: ['Website', 'Telefoon', 'E-mail', 'WhatsApp', 'Handmatig'],
      required: true,
    },
    {
      name: 'priority',
      label: 'Prioriteit',
      type: 'select',
      options: ['Normaal', 'Hoog', 'Urgent'],
      defaultValue: 'Normaal',
      required: true,
      access: staffManaged,
    },
    workflow(['Nieuw', 'In behandeling', 'Doorgestuurd', 'Beantwoord', 'Afgesloten'], 'Nieuw'),
    {
      name: 'unread',
      label: 'Ongelezen door medewerker',
      type: 'checkbox',
      defaultValue: true,
      access: staffManaged,
    },
    {
      name: 'specialist',
      label: 'Toegewezen specialist / afdeling',
      type: 'text',
      access: staffManaged,
    },
    relation('booking', 'Boeking', 'bookings', false),
    relation('trip', 'Voorgestelde reis', 'trips', false),
    { name: 'destinationLabel', label: 'Gewenste bestemming', type: 'text' },
    { name: 'periodLabel', label: 'Gewenste periode', type: 'text' },
    { name: 'departureLabel', label: 'Vertrekinformatie zoals opgegeven', type: 'text' },
    integer('travellers', 'Aantal reizigers', 1, 20),
    { name: 'budgetLabel', label: 'Budget zoals opgegeven', type: 'text' },
    money('budgetMax', 'Maximaal budget'),
    { name: 'startDate', label: 'Vertrekdatum', type: 'date' },
    { name: 'endDate', label: 'Terugkomstdatum', type: 'date' },
    { name: 'receivedAt', label: 'Werkelijk ontvangen op (indien bekend)', type: 'date' },
    legacyLabels(),
  ],
}
